function R = cc_clinical_modifier_models(W)
%CC_CLINICAL_MODIFIER_MODELS Public wrapper preserving supplied model logic.
% Prepared primary-only table from cc_join_clinical_inputs. Centering uses
% joined regional observations (NOT one value per patient), as in the source.
% Missing covariates remain NaN; each fit uses its own complete rows.
required={'CaseNo','CaseNum','State','Region','mean_MeanWTC_4_13', ...
    'AgeOnset','AgeSurgery','Duration'};
assert(istable(W)&&all(ismember(required,W.Properties.VariableNames)), ...
    'CCClinical:ModelColumns','Prepared model table required.');
% The following centered/standardized definitions preserve source code.
W.AgeOnset_c = W.AgeOnset - mean(W.AgeOnset,'omitnan');
W.AgeSurgery_c = W.AgeSurgery - mean(W.AgeSurgery,'omitnan');
W.Duration_c = W.Duration - mean(W.Duration,'omitnan');
W.AgeOnset_z = ...
    (W.AgeOnset - mean(W.AgeOnset,'omitnan')) ./ ...
    std(W.AgeOnset,'omitnan');
W.Duration_z = ...
    (W.Duration - mean(W.Duration,'omitnan')) ./ ...
    std(W.Duration,'omitnan');
assert(std(W.AgeOnset,'omitnan')>0 && std(W.Duration,'omitnan')>0 && ...
    std(W.AgeSurgery,'omitnan')>0,'CCClinical:NoVariation', ...
    'Clinical covariates need nonzero variation.');
labels=["AgeOnset","AgeSurgery","Duration","Joint","JointZ"];
formulas={ ...
    'mean_MeanWTC_4_13 ~ State*AgeOnset_c + Region + (1|CaseNo) + (1|CaseNo:Region)', ...
    'mean_MeanWTC_4_13 ~ State*AgeSurgery_c + Region + (1|CaseNo) + (1|CaseNo:Region)', ...
    'mean_MeanWTC_4_13 ~ State*Duration_c + Region + (1|CaseNo) + (1|CaseNo:Region)', ...
    'mean_MeanWTC_4_13 ~ State*AgeOnset_c + State*Duration_c + Region + (1|CaseNo) + (1|CaseNo:Region)', ...
    'mean_MeanWTC_4_13 ~ State*AgeOnset_z + State*Duration_z + Region + (1|CaseNo) + (1|CaseNo:Region)'};
models=cell(5,1);at=table;ct=table;warnRows=cell(0,4);
for k=1:5
    lastwarn('','');
    % Explicit ML equals the supplied fitlme default; no optimizer change.
    m=fitlme(W,formulas{k},'FitMethod','ML');
    A=anova(m,'DFMethod','satterthwaite');C=m.Coefficients;
    [wm,wi]=lastwarn;
    models{k}=m;
    na=numel(A.Term);nc=numel(C.Name);
    a=table(repmat(labels(k),na,1),string(A.Term),A.FStat,A.DF1,A.DF2,A.pValue, ...
        repmat(m.NumObservations,na,1),repmat("ML",na,1), ...
        repmat("Satterthwaite",na,1),'VariableNames', ...
        {'Model','Term','FStat','DF1','DF2','P_Unadjusted','N_Observations','FitMethod','DFMethod'});
    c=table(repmat(labels(k),nc,1),string(C.Name),C.Estimate,C.SE,C.tStat,C.DF, ...
        C.pValue,C.Lower,C.Upper,repmat("Residual",nc,1),'VariableNames', ...
        {'Model','Term','Estimate','SE','tStat','DF','P_Unadjusted','CI_Lower','CI_Upper','DFMethod'});
    if isempty(at),at=a;else,at=[at;a];end %#ok<AGROW>
    if isempty(ct),ct=c;else,ct=[ct;c];end %#ok<AGROW>
    warnRows(end+1,:)={labels(k),~isempty(wm),string(wi),string(wm)}; %#ok<AGROW>
end
patientCov = unique(W(:,{'CaseNum','AgeOnset','AgeSurgery','Duration'}),'rows');
X = [patientCov.AgeOnset,patientCov.AgeSurgery,patientCov.Duration];
[Rho,Pcorr] = corr(X,'Type','Spearman','Rows','pairwise');
R=struct;
R.ModelData=W;R.Models=models;R.Labels=labels;R.ANOVA=at;R.Coefficients=ct;
R.CovariateRho=Rho;R.CovariateP=Pcorr;
R.Warnings=cell2table(warnRows,'VariableNames', ...
    {'Model','WarningOccurred','WarningIdentifier','WarningMessage'});
end
